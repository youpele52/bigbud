import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { execFileSync } from "node:child_process";

const root = fileURLToPath(new URL("../src/provider/Layers/OpencodeV2/", import.meta.url));
const output = path.join(root, "Orchestration.implementation.manifest.generated.ts");
const common = ["Orchestration.implementation.types.ts", "Orchestration.plugin.specs.ts"];
const closures = {
  v1: [...common, "Orchestration.implementation.v1.ts"],
  v2: [...common, "Orchestration.implementation.v1.ts", "Orchestration.implementation.v2.ts"],
} as const;
const sha = (value: string) => createHash("sha256").update(value).digest("hex");
const schemaDigest = sha(await readFile(path.join(root, "Orchestration.plugin.specs.ts"), "utf8"));
const descriptor = {
  format: "bigbud.thread.implementation.sources.v1",
  bootstrapAbi: "bigbud.thread.bootstrap.v1",
  canonicalRequestAbi: "bigbud.thread.canonical.v1",
  resultEncoding: "bigbud.thread.final-json.v1",
  schemaDigest,
};
const entries: Record<string, unknown> = {};
for (const [version, modules] of Object.entries(closures)) {
  const sources = await Promise.all(
    [...modules].toSorted().map(async (name) => {
      const content = await readFile(path.join(root, name), "utf8");
      if (content.split("\n").length > 401)
        throw new Error("Implementation closure module exceeds 400 lines.");
      // Executable imports must be literal local members of this exact closed allowlist.
      const imports = [
        ...content.matchAll(/import\s+(?!type\b)[\s\S]*?from\s+["']([^"']+)["']/g),
      ].map((match) => match[1]!);
      if (
        /\bimport\s*\(|\brequire\s*\(/.test(content) ||
        imports.some(
          (specifier) => !specifier.startsWith("./") || !modules.includes(specifier.slice(2)),
        )
      )
        throw new Error(
          "Implementation source runtime dependency closure changed; declare/freeze a new version.",
        );
      return [name, sha(content)] as const;
    }),
  );
  entries[version] = {
    ...descriptor,
    implementationDigest: sha(JSON.stringify([descriptor, sources])),
    sources,
  };
}
const source = `// Generated by scripts/generateThreadToolImplementationManifest.ts; do not hand edit.\nexport const V2_IMPLEMENTATION_MANIFEST = ${JSON.stringify(entries, null, 2)} as const;\n`;
const repository = fileURLToPath(new URL("../../../", import.meta.url));
const formatterCli = fileURLToPath(
  new URL("./bin/oxfmt", import.meta.resolve("oxfmt/package.json")),
);
const generated = execFileSync(process.execPath, [formatterCli, "--stdin-filepath", output], {
  cwd: repository,
  input: source,
  encoding: "utf8",
  maxBuffer: 1048576,
});
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8").catch(() => "")) !== generated)
    throw new Error(
      "Frozen thread-tool implementation manifest drift; regenerate an intentional new version before build.",
    );
} else await writeFile(output, generated);
