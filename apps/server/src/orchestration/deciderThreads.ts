/**
 * Decider cases for thread-scoped commands.
 *
 * Handles all thread.* commands.
 */
import type {
  OrchestrationCommand,
  OrchestrationEvent,
  OrchestrationReadModel,
} from "@bigbud/contracts";
import { Effect } from "effect";

import { OrchestrationCommandInvariantError } from "./Errors.ts";
import {
  type ThreadLifecycleCommand,
  decideThreadLifecycleCommand,
} from "./deciderThreads.lifecycle.ts";
import { type ThreadTurnCommand, decideThreadTurnCommand } from "./deciderThreads.turn.ts";
import { decideThreadTaskCommand } from "./deciderThreads.tasks.ts";
import { decideThreadForkCommand } from "./deciderThreads.fork.ts";
import { decideDelegationModelChoiceCommand } from "./deciderThreads.delegationModelChoice.ts";
import { decideThreadRecoveryCommand } from "./deciderThreads.recovery.ts";
import {
  canNameThreadFromTerminal,
  TERMINAL_TITLE_COMMAND_PREFIX,
  threadTitleOwner,
} from "../orchestration-tools/TerminalThreadTitle.ts";
import {
  isAutoGeneratedTitleCommand,
  isProviderThreadMetadataTitleCommand,
  isThreadTitleLocked,
} from "../orchestration-tools/ThreadTitleLock.ts";

const LIFECYCLE_TYPES = new Set([
  "thread.create",
  "thread.delete",
  "thread.delete.finalize",
  "thread.delete.abort",
  "thread.retention-delete",
  "thread.archive",
  "thread.unarchive",
  "thread.pin",
  "thread.unpin",
  "thread.pin.migrate",
  "thread.meta.update",
  "thread.runtime-mode.set",
  "thread.interaction-mode.set",
]);

export const decideThreadCommand = Effect.fn("decideThreadCommand")(function* ({
  command,
  readModel,
}: {
  readonly command: Exclude<
    OrchestrationCommand,
    {
      type:
        | "project.create"
        | "project.meta.update"
        | "project.reconfigure"
        | "project.delete"
        | "project.delete.finalize"
        | "project.delete.abort";
    }
  >;
  readonly readModel: OrchestrationReadModel;
}): Effect.fn.Return<
  Omit<OrchestrationEvent, "sequence"> | ReadonlyArray<Omit<OrchestrationEvent, "sequence">>,
  OrchestrationCommandInvariantError
> {
  if (command.type === "thread.meta.update" && command.title !== undefined) {
    const terminalTitle = command.commandId.startsWith(TERMINAL_TITLE_COMMAND_PREFIX);
    const thread = readModel.threads.find((item) => item.id === command.threadId);
    // Check at the serialized decision boundary: callbacks may have read stale state.
    if (terminalTitle && (!thread || !canNameThreadFromTerminal(thread))) return [];
    if (
      !terminalTitle &&
      (isThreadTitleLocked(command.threadId) ||
        (thread && ["terminal", "manual"].includes(threadTitleOwner(thread) ?? ""))) &&
      (isAutoGeneratedTitleCommand(command.commandId) ||
        isProviderThreadMetadataTitleCommand(command.commandId))
    ) {
      const { title, ...metadata } = command;
      void title;
      return yield* decideThreadLifecycleCommand({ command: metadata, readModel });
    }
  }
  if (LIFECYCLE_TYPES.has(command.type)) {
    return yield* decideThreadLifecycleCommand({
      command: command as ThreadLifecycleCommand,
      readModel,
    });
  }
  if (command.type === "thread.fork") {
    return yield* decideThreadForkCommand({ command, readModel });
  }
  if (
    command.type === "thread.delegation.model-choice.hold" ||
    command.type === "thread.delegation.model-choice.expire" ||
    command.type === "thread.delegation.model-choice.pick"
  ) {
    return yield* decideDelegationModelChoiceCommand({ command, readModel });
  }
  if (command.type === "thread.task.upsert" || command.type === "thread.task.remove") {
    return yield* decideThreadTaskCommand({ command, readModel });
  }
  if (command.type === "thread.recovery.set" || command.type === "thread.recovery.resolve") {
    return yield* decideThreadRecoveryCommand({ command, readModel });
  }
  return yield* decideThreadTurnCommand({
    command: command as ThreadTurnCommand,
    readModel,
  });
});
