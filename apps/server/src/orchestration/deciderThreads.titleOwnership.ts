import { EventId } from "@bigbud/contracts/core/baseSchemas.ts";
import type { OrchestrationCommand } from "@bigbud/contracts/orchestration/orchestration.commands.ts";
import type { OrchestrationEvent } from "@bigbud/contracts/orchestration/orchestration.events.ts";
import type { OrchestrationReadModel } from "@bigbud/contracts/orchestration/orchestration.thread.ts";
import {
  TERMINAL_TITLE_COMMAND_PREFIX,
  TITLE_OWNERSHIP_ACTIVITY,
  threadTitleOwner,
  type ThreadTitleOwner,
} from "../orchestration-tools/TerminalThreadTitle.ts";
import {
  isAutoGeneratedTitleCommand,
  isProviderThreadMetadataTitleCommand,
} from "../orchestration-tools/ThreadTitleLock.ts";
import { withEventBase } from "./deciderHelpers.ts";

/** Commit the naming source in the same transaction as the evidence that claimed it. */
export function withThreadTitleOwnership(
  command: OrchestrationCommand,
  model: OrchestrationReadModel,
  result:
    | Omit<OrchestrationEvent, "sequence">
    | ReadonlyArray<Omit<OrchestrationEvent, "sequence">>,
): typeof result {
  if (!("threadId" in command)) return result;
  const events = (Array.isArray(result) ? result : [result]) as ReadonlyArray<OrchestrationEvent>;
  if (!events.length) return result;
  const thread = model.threads.find((item) => item.id === command.threadId);
  const owner = thread ? threadTitleOwner(thread) : null;
  let source: ThreadTitleOwner | null = null;
  if (command.type === "thread.meta.update" && command.title?.trim()) {
    if (command.commandId.startsWith(TERMINAL_TITLE_COMMAND_PREFIX)) source = "terminal";
    else if (
      !isAutoGeneratedTitleCommand(command.commandId) &&
      !isProviderThreadMetadataTitleCommand(command.commandId)
    )
      source = "manual";
  }
  if (
    !source &&
    !owner &&
    thread &&
    /^(?:New thread|New chat)$/.test(thread.title.trim()) &&
    events.some((event) => {
      if (event.type === "thread.message-sent") {
        return (
          event.payload.role === "user" &&
          (!!event.payload.text.trim() || !!event.payload.attachments?.length)
        );
      }
      if (event.type === "thread.prompt-queued") {
        return !!event.payload.prompt.text.trim() || !!event.payload.prompt.attachments?.length;
      }
      return false;
    })
  )
    source = "chat";
  if (!source || (owner && source !== "manual")) return result;
  const first = events[0]!;
  return [
    ...events,
    {
      ...withEventBase({
        aggregateKind: "thread",
        aggregateId: command.threadId,
        commandId: command.commandId,
        occurredAt: first.occurredAt,
      }),
      type: "thread.activity-appended",
      payload: {
        threadId: command.threadId,
        activity: {
          id: EventId.makeUnsafe(`thread-title-owner:${command.threadId}`),
          kind: TITLE_OWNERSHIP_ACTIVITY,
          tone: "info",
          summary: `Thread naming source: ${source}`,
          payload: { source },
          turnId: null,
          createdAt: first.occurredAt,
        },
      },
    },
  ];
}
