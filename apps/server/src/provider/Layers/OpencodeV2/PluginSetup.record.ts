import { createHash, sign } from "node:crypto";
import { Schema } from "effect";
import type { exportV2ThreadArtifact } from "./Orchestration.artifact.ts";
import { v2ThreadRegistration, v2OwnerRegistration } from "./Orchestration.registration.ts";

export type V2PluginSetupArtifact = Awaited<ReturnType<typeof exportV2ThreadArtifact>>;
export const V2_MANAGED_PLUGIN_FILENAME = "bigbud-thread-tools-managed.js";
const Hex = Schema.String.check(Schema.isPattern(/^[a-f0-9]{64}$/));
const Bounded = Schema.String.check(Schema.isMinLength(1), Schema.isMaxLength(4096));
const Identity = Schema.Union([
  Schema.Struct({ dev: Schema.Int, ino: Schema.Int }),
  Schema.Struct({
    dev: Schema.String.check(Schema.isPattern(/^[a-f0-9]{16}$/)),
    ino: Schema.String.check(Schema.isPattern(/^[a-f0-9]{32}$/)),
  }),
]);
const Entry = Schema.Struct({
  content: Schema.String.check(Schema.isMinLength(1), Schema.isMaxLength(16384)),
  hash: Hex,
  issuer: Hex,
  artifactDigest: Hex,
  artifactDirectoryUri: Bounded,
});
export const V2PluginPublication = Schema.Struct({
  protocol: Schema.Literals(["bigbud.thread.install.v1", "bigbud.thread.install.v2"]),
  root: Bounded,
  rootIdentity: Identity,
  pluginsIdentity: Identity,
  phase: Schema.Literals(["reserved", "publishing", "committed"]),
  previous: Schema.NullOr(Entry),
  next: Entry,
  previousIdentity: Schema.NullOr(Identity),
  nextIdentity: Schema.NullOr(Identity),
});
export type V2PluginPublication = typeof V2PluginPublication.Type;
export const v2ManagedPluginFilename = (artifact: V2PluginSetupArtifact) =>
  v2ThreadRegistration(artifact).filename;
export const v2PublicationFilename = (record: V2PluginPublication) =>
  v2OwnerRegistration({
    issuer: record.next.issuer,
    bootstrapAbi:
      record.protocol === "bigbud.thread.install.v2"
        ? "bigbud.thread.bootstrap.v2"
        : "bigbud.thread.bootstrap.v1",
  }).filename;
export const v2PublicationProtocol = (artifact: V2PluginSetupArtifact) =>
  v2ThreadRegistration(artifact).family === "scoped"
    ? ("bigbud.thread.install.v2" as const)
    : ("bigbud.thread.install.v1" as const);
export const v2PluginContentHash = (content: string) =>
  createHash("sha256").update(content).digest("hex");

/** A name/comment is not provenance; app records and the exact signed generated bytes must agree. */
export function v2ManagedPluginEntry(artifact: V2PluginSetupArtifact, root: string) {
  const metadata = [
    v2PublicationProtocol(artifact),
    root,
    artifact.issuer,
    artifact.artifactDigest,
    artifact.pluginUri,
    artifact.entryUri,
  ];
  const signature = sign(null, Buffer.from(JSON.stringify(metadata)), artifact.privateKey).toString(
    "base64url",
  );
  const content = `// bigbud-required-plugin.${v2ThreadRegistration(artifact).family === "scoped" ? "v2" : "v1"} ${JSON.stringify({ metadata, signature })}\nexport {default} from ${JSON.stringify(artifact.entryUri)};\n`;
  if (Buffer.byteLength(content) > 16384)
    throw new Error("V2 required-plugin entry exceeds its byte bound.");
  try {
    return Schema.decodeUnknownSync(Entry)({
      content,
      hash: v2PluginContentHash(content),
      issuer: artifact.issuer,
      artifactDigest: artifact.artifactDigest,
      artifactDirectoryUri: artifact.pluginUri,
    });
  } catch {
    throw new Error("V2 required-plugin entry/URI exceeds safe publication bounds.");
  }
}
