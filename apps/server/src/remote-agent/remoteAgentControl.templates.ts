import {
  compileRemoteAgentControlOp,
  type RemoteAgentControlOp,
} from "./remoteAgentControl.ops.ts";
import {
  compileRemoteAgentInstallControlOp,
  type RemoteAgentInstallControlOp,
} from "./remoteAgentControl.ops.install.ts";
import {
  AGENT_CONTROL_TEMPLATE_SPECS,
  SENTINEL,
  type AgentControlTemplateSpec,
} from "./remoteAgentControl.templates.specs.ts";

/**
 * U25 owner templates, generated from the legacy builders. Each spec compiles its
 * legacy script with sentinel operands; every sentinel is then replaced by a shell
 * variable that a generated header binds from one positional argument. The owner
 * runs exactly this text (`include_str!`), so the owner and the legacy runner share
 * one source. A sentinel left behind, or one outside a quoted word where only a
 * quoted word is safe, fails generation.
 */
export const AGENT_CONTROL_TEMPLATE_DIR =
  "crates/bigbud-ssh-owner/src/bin/ssh_owner/owner_agent_control/templates";

const RUNTIME_FIELDS = [
  "generation",
  "version",
  "sha256",
  "build_digest",
  "target_triple",
  "binary",
  "state",
  "socket",
  "log",
  "origin",
] as const;

const quote = (value: string) => `'${value.replaceAll("'", "'\\''")}'`;

function header(spec: AgentControlTemplateSpec): string {
  const names = [...(spec.runtime ? RUNTIME_FIELDS : []), ...spec.operands];
  const lines = [
    `# Generated by apps/server/src/remote-agent/remoteAgentControl.templates.ts from the`,
    `# legacy ${spec.source} script. Do not edit; regenerate (U25).`,
    `[ "$#" -eq ${names.length} ] || exit 64`,
    'bigbud_arg_root=$(readlink -f -- "$HOME")/.bigbud/agent',
    ...names.map((name, index) => `bigbud_arg_${name}="\${${index + 1}}"`),
  ];
  if (!spec.runtime && spec.allowed.includes("binary")) {
    lines.push(
      "bigbud_arg_binary=$bigbud_arg_root/bin/$bigbud_arg_version/$bigbud_arg_sha256/bigbud-remote-agent",
    );
  }
  if (spec.runtime) {
    lines.push(
      'case "$bigbud_arg_origin" in',
      '  managed) test "$bigbud_arg_binary" = "$bigbud_arg_root/bin/$bigbud_arg_version/$bigbud_arg_sha256/bigbud-remote-agent" &&',
      '    test "$bigbud_arg_state" = "$bigbud_arg_root/runtimes/$bigbud_arg_generation" || exit 86 ;;',
      '  legacy-external) test "$bigbud_arg_state" = "$bigbud_arg_root/state" || exit 86 ;;',
      "  *) exit 86 ;;",
      "esac",
      'test "$bigbud_arg_socket" = "$bigbud_arg_state/supervisor.sock" &&',
      '  test "$bigbud_arg_log" = "$bigbud_arg_state/supervisor.log" || exit 86',
    );
  }
  return `${lines.join("\n")}\n`;
}

/** Replace every sentinel with its variable; longest values first so paths win over parts. */
function templatize(spec: AgentControlTemplateSpec, script: string): string {
  let text = script;
  for (const transform of spec.transforms ?? []) {
    if (!text.includes(transform.from)) throw new Error(`${spec.file}: transform source not found`);
    text = text.replaceAll(transform.from, transform.to);
  }
  const values = Object.entries(SENTINEL.values)
    .filter(([name]) => (spec.allowed as ReadonlyArray<string>).includes(name))
    .toSorted(([, left], [, right]) => right.length - left.length);
  for (const [name, value] of values) {
    text = text.replaceAll(quote(value), `"$bigbud_arg_${name}"`);
    if ((SENTINEL.bare as ReadonlyArray<string>).includes(name))
      text = text.replaceAll(value, `\${bigbud_arg_${name}}`);
  }
  for (const marker of SENTINEL.markers) {
    if (text.includes(marker)) throw new Error(`${spec.file}: unbound sentinel ${marker}`);
  }
  return text;
}

function compile(spec: AgentControlTemplateSpec): string {
  const op = spec.op;
  return isInstallOp(op)
    ? compileRemoteAgentInstallControlOp(op)
    : compileRemoteAgentControlOp(SENTINEL.values.root, op);
}

function isInstallOp(
  op: RemoteAgentControlOp | RemoteAgentInstallControlOp,
): op is RemoteAgentInstallControlOp {
  return [
    "platformProbe",
    "readOnlyStatus",
    "installUpload",
    "placedProbe",
    "inboxAdopt",
    "identityCheck",
    "binaryCheck",
  ].includes(op.kind);
}

/** File name → generated template text, in spec order. */
export function renderAgentControlTemplates(): ReadonlyMap<string, string> {
  const files = new Map<string, string>();
  for (const spec of AGENT_CONTROL_TEMPLATE_SPECS) {
    if (files.has(spec.file)) throw new Error(`duplicate template ${spec.file}`);
    files.set(spec.file, `${header(spec)}${templatize(spec, compile(spec))}\n`);
  }
  return files;
}
