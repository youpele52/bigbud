import { useState } from "react";
import { useMobileHosts } from "../../context/MobileHostsContext";
import { MobileHostSwitcher } from "./MobileHostSwitcher";
import { MobileHostAdmissionActions } from "./MobileHostAdmissionScreen.actions";
import { MobileCard, MobileMuted, MobilePage, MobileTitle } from "./MobileShell";

export function MobileHostAdmissionScreen() {
  const context = useMobileHosts();
  const selected = context?.hosts.selected ?? null;
  const [target, setTarget] = useState({ selected, generation: 0 });
  // A new selected connection retires its confirmation before children can commit.
  // Keep credentials out of DOM/React keys, including same-authority renewal.
  if (target.selected !== selected) setTarget({ selected, generation: target.generation + 1 });
  if (!context?.hosts.selected) return null;
  const { hosts, admission } = context;
  return (
    <MobilePage className="min-w-0">
      <MobileCard className="min-w-0">
        <div className="flex min-w-0 items-center justify-between gap-2">
          <MobileTitle>
            {admission.status === "checking"
              ? "Verifying backend identity"
              : "Cannot connect to this host"}
          </MobileTitle>
          <MobileHostSwitcher />
        </div>
        <MobileMuted className="mt-2 [overflow-wrap:anywhere]">
          {hosts.selected?.backendOrigin}
        </MobileMuted>
        <p className="mt-2 break-all text-xs text-muted-foreground">
          Authority: {hosts.selected?.pin.authority.authorityId}
        </p>
        {admission.error ? (
          <p className="mt-3 text-sm text-warning" role="alert">
            {admission.error}
          </p>
        ) : null}
        {hosts.error ? (
          <p className="mt-3 text-sm text-destructive" role="alert">
            {hosts.error}
          </p>
        ) : null}
        <MobileHostAdmissionActions key={target.generation} context={context} />
        <MobileMuted className="mt-3">
          Mobile access must be enabled and ready on this host. To renew its authorization, open a
          fresh pairing link generated by that host.
        </MobileMuted>
      </MobileCard>
    </MobilePage>
  );
}
