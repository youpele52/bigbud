/**
 * Builds bigbud's agent cursor theme for the cua-driver overlay.
 *
 *   bun scripts/cua-cursor-theme/build.ts
 *     Regenerates the dotLottie source only.
 *   bun scripts/cua-cursor-theme/build.ts --compiler <cua-driver> [--preview <dir>]
 *     Also validates and compiles it, then regenerates the desktop artifact module.
 *
 * `<cua-driver>` must be the pinned release's full (non `-binary`) archive
 * executable, which ships the `cua-cursor-theme` authoring sidecar beside it.
 * bigbud installs only the bare binary, so compiling is a development step and
 * the compiled artifact is checked in, as upstream does for `cua.default`.
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { CUA_CURSOR_THEME_ID } from "@bigbud/shared/cua-driver/cursorTheme";

import { cursorAnimations, cursorSemanticManifest } from "./bigbudCursor.ts";
import { dotLottieArchive } from "./dotLottie.ts";

const SCRIPT_DIR = fileURLToPath(new URL(".", import.meta.url));
export const SOURCE_PATH = join(SCRIPT_DIR, "assets", `${CUA_CURSOR_THEME_ID}.lottie`);
export const COMPILED_PATH = join(SCRIPT_DIR, "assets", `${CUA_CURSOR_THEME_ID}.cua-theme`);
export const ARTIFACT_MODULE_PATH = resolve(
  SCRIPT_DIR,
  "../../apps/desktop/src/backend/cuaDriver.cursorTheme.artifact.ts",
);

export function buildCursorSource(): Buffer {
  return dotLottieArchive({
    generator: "bigbud scripts/cua-cursor-theme/build.ts",
    semanticManifest: cursorSemanticManifest(),
    animations: cursorAnimations(),
  });
}

export function artifactModuleSource(compiled: Buffer): string {
  const sha256 = createHash("sha256").update(compiled).digest("hex");
  return [
    "// Generated by scripts/cua-cursor-theme/build.ts from",
    `// scripts/cua-cursor-theme/assets/${CUA_CURSOR_THEME_ID}.cua-theme. Do not edit.`,
    "",
    "export const CUA_CURSOR_THEME_ARTIFACT_SHA256 =",
    `  "${sha256}";`,
    "",
    "export const CUA_CURSOR_THEME_ARTIFACT_BASE64 =",
    `  "${compiled.toString("base64")}";`,
    "",
  ].join("\n");
}

function compile(compiler: string, args: ReadonlyArray<string>): void {
  const result = spawnSync(compiler, ["cursor-theme", ...args], {
    cwd: tmpdir(),
    stdio: "inherit",
  });
  if (result.status !== 0) {
    throw new Error(`cua-driver cursor-theme ${args[0]} failed (status ${result.status}).`);
  }
}

function flag(name: string): string | undefined {
  const index = process.argv.indexOf(name);
  return index === -1 ? undefined : process.argv[index + 1];
}

function main(): void {
  writeFileSync(SOURCE_PATH, buildCursorSource());
  console.log(`wrote ${SOURCE_PATH}`);
  const compiler = flag("--compiler");
  if (!compiler) return;

  compile(compiler, ["validate", SOURCE_PATH]);
  // Build into a scratch directory so a failed compile never leaves a partial artifact.
  const scratch = mkdtempSync(join(tmpdir(), "bigbud-cursor-theme-"));
  try {
    const built = join(scratch, `${CUA_CURSOR_THEME_ID}.cua-theme`);
    compile(compiler, ["build", SOURCE_PATH, "--output", built]);
    compile(compiler, ["inspect", built]);
    const preview = flag("--preview");
    if (preview) compile(compiler, ["preview", built, "--output", resolve(preview)]);
    const compiled = readFileSync(built);
    writeFileSync(COMPILED_PATH, compiled);
    writeFileSync(ARTIFACT_MODULE_PATH, artifactModuleSource(compiled));
    console.log(`wrote ${COMPILED_PATH} (${compiled.length} bytes)`);
    console.log(`wrote ${ARTIFACT_MODULE_PATH}`);
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

if (import.meta.main) main();
