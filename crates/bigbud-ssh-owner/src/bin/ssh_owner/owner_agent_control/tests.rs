#![allow(clippy::expect_used)]

use super::recipe;
use crate::v1::{
    AgentControlKind as Kind, AgentControlOpen, AgentObserveMode as Mode, AgentRuntime,
    AgentRuntimeOrigin, ErrorCode,
};

const SHA: &str = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";
const ROOT: &str = "/home/dev/.bigbud/agent";

fn runtime(origin: AgentRuntimeOrigin) -> AgentRuntime {
    let state = format!("{ROOT}/runtimes/g-1");
    AgentRuntime {
        generation: "g-1".into(),
        version: "0.9.0".into(),
        sha256: SHA.into(),
        build_digest: "build:abc".into(),
        target_triple: "aarch64-unknown-linux-gnu".into(),
        binary_path: format!("{ROOT}/bin/0.9.0/{SHA}/bigbud-remote-agent"),
        socket_path: format!("{state}/supervisor.sock"),
        log_path: format!("{state}/supervisor.log"),
        state_path: state,
        origin: origin as i32,
    }
}

fn open(kind: Kind) -> AgentControlOpen {
    AgentControlOpen {
        lease: vec![7; 32],
        kind: kind as i32,
        ..AgentControlOpen::default()
    }
}

fn with_runtime(kind: Kind) -> AgentControlOpen {
    AgentControlOpen {
        runtime: Some(runtime(AgentRuntimeOrigin::Managed)),
        ..open(kind)
    }
}

#[test]
fn operand_free_kinds_compile_to_the_fixed_login_shell_frame() {
    for kind in [
        Kind::ControlRoot,
        Kind::RegistryRead,
        Kind::Inventory,
        Kind::RemovalResume,
        Kind::RemovalOutcome,
        Kind::HostClock,
        Kind::BackendRuntimeProbe,
        Kind::RuntimeProbe,
        Kind::PlatformProbe,
        Kind::ReadOnlyStatus,
    ] {
        let recipe = recipe(&open(kind)).expect("compiles");
        assert!(recipe.command.starts_with("exec sh -lc '# Generated by"));
        assert!(recipe.command.ends_with(" bigbud-agent-control"));
        assert!(!recipe.streamed_input);
    }
}

#[test]
fn every_kind_refuses_an_operand_outside_its_own_set() {
    let mut extra = open(Kind::RegistryRead);
    extra.fence_id = "fence-0001".into();
    assert_eq!(recipe(&extra).err(), Some(ErrorCode::InvalidOperands));
    let mut extra = with_runtime(Kind::SupervisorShutdown);
    extra.attempt_id = "a-1".into();
    assert_eq!(recipe(&extra).err(), Some(ErrorCode::InvalidOperands));
    let mut extra = open(Kind::HostClock);
    extra.runtime = Some(runtime(AgentRuntimeOrigin::Managed));
    assert_eq!(recipe(&extra).err(), Some(ErrorCode::InvalidOperands));
    assert_eq!(
        recipe(&open(Kind::Unspecified)).err(),
        Some(ErrorCode::InvalidOperands)
    );
}

#[test]
fn runtime_kinds_pass_the_descriptor_and_their_own_operands_only() {
    let mut observe = with_runtime(Kind::SupervisorObserve);
    observe.observe_mode = Mode::CandidateStartup as i32;
    observe.attempt_id = "launch-g-1".into();
    let command = recipe(&observe).expect("compiles").command;
    assert!(command.ends_with(&format!(
        "'{ROOT}/runtimes/g-1/supervisor.log' 'managed' 'launch-g-1'"
    )));
    observe.observe_mode = Mode::Unspecified as i32;
    assert_eq!(recipe(&observe).err(), Some(ErrorCode::InvalidOperands));
    let mut bad = with_runtime(Kind::StateAbsent);
    bad.runtime.as_mut().expect("runtime").state_path = format!("{ROOT}/runtimes/../x");
    assert_eq!(recipe(&bad).err(), Some(ErrorCode::InvalidOperands));
    let mut bad = with_runtime(Kind::StateAbsent);
    bad.runtime.as_mut().expect("runtime").generation = "G".into();
    assert_eq!(recipe(&bad).err(), Some(ErrorCode::InvalidOperands));
}

#[test]
fn launches_and_deletion_require_a_managed_runtime() {
    for kind in [Kind::IsolatedLaunch, Kind::RetirementDelete] {
        let mut request = open(kind);
        request.runtime = Some(runtime(AgentRuntimeOrigin::LegacyExternal));
        if kind == Kind::IsolatedLaunch {
            request.attempt_id = "a-1".into();
        }
        assert_eq!(recipe(&request).err(), Some(ErrorCode::InvalidOperands));
    }
    let mut shutdown = open(Kind::SupervisorShutdown);
    shutdown.runtime = Some(runtime(AgentRuntimeOrigin::LegacyExternal));
    assert!(recipe(&shutdown).is_ok());
}

#[test]
fn streamed_kinds_carry_identity_only_and_listen_for_bytes() {
    let mut cas = open(Kind::RegistryCas);
    cas.next_size = 10;
    cas.next_sha256 = SHA.into();
    let absent = recipe(&cas).expect("absent");
    assert!(absent.streamed_input);
    assert!(absent.command.contains("registry_cas") || absent.command.contains("cat > \"$next\""));
    cas.expected_present = true;
    cas.expected_size = 4;
    cas.expected_sha256 = SHA.into();
    assert!(recipe(&cas).expect("present").command.contains("head -c"));
    cas.next_size = 1024 * 1024 + 1;
    assert_eq!(recipe(&cas).err(), Some(ErrorCode::InvalidOperands));

    let mut upload = open(Kind::InstallUpload);
    upload.version = "0.9.0".into();
    upload.sha256 = SHA.into();
    upload.size = 4096;
    upload.reservation_id = "stage-1".into();
    let compiled = recipe(&upload).expect("upload");
    assert!(compiled.streamed_input);
    assert!(compiled.command.ends_with("'0.9.0' '0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef' '4096' 'stage-1'"));
    upload.size = 0;
    assert_eq!(recipe(&upload).err(), Some(ErrorCode::InvalidOperands));
}

#[test]
fn ids_follow_the_legacy_patterns() {
    let mut removal = open(Kind::Removal);
    removal.fence_id = "short".into();
    assert_eq!(recipe(&removal).err(), Some(ErrorCode::InvalidOperands));
    removal.fence_id = "fence-0001".into();
    assert_eq!(recipe(&removal).expect("fence").deadline.as_secs(), 600);
    let mut fence = open(Kind::StageFenceRevoke);
    fence.reservation_id = "has space".into();
    assert_eq!(recipe(&fence).err(), Some(ErrorCode::InvalidOperands));
    let mut probe = open(Kind::RuntimeProbe);
    probe.binary_path = "relative/agent".into();
    assert_eq!(recipe(&probe).err(), Some(ErrorCode::InvalidOperands));
    probe.binary_path = "/opt/agent/bigbud-remote-agent".into();
    assert!(
        recipe(&probe)
            .expect("external")
            .command
            .ends_with("'/opt/agent/bigbud-remote-agent'")
    );
}
